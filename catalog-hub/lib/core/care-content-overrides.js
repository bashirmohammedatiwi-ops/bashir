export function getCareOverride(barcode = '') {
  const key = String(barcode).trim();
  return OVERRIDES[key] || BATCH_LARGE_OVERRIDES[key] || BATCH49_OVERRIDES[key] || BATCH51_OVERRIDES[key] || BATCH140_OVERRIDES[key] || null;
}

export function resolveOverrideCategories(barcode = '') {
  const o = getCareOverride(barcode);
  if (!o) return null;
  return {
    subcategorySlugs: o.subcategorySlugs || [],
    tertiarySlugs: o.tertiarySlugs || [],
    typeKey: o.typeKey || '',
  };
}
