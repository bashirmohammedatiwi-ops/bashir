export function getPremiumMeta(barcode = '') {
  const digits = String(barcode).replace(/\D/g, '');
  return PREMIUM_META[barcode]
    || PREMIUM_META[digits]
    || PREMIUM_META[digits.replace(/^0+/, '')]
    || null;
}

export function buildPremiumDescriptions(meta, storeAr = '', storeEn = '') {
  if (storeAr?.length >= 40 && storeEn?.length >= 40) {
    return { descriptionAr: storeAr, descriptionEn: storeEn };
  }
  if (!meta) return { descriptionAr: storeAr, descriptionEn: storeEn };
  const catAr = meta.kind === 'perfume' ? 'عطور فاخرة' : meta.kind === 'makeup' ? 'مكياج فاخر' : 'عناية فاخرة';
  const catEn = meta.kind === 'perfume' ? 'Luxury Perfumes' : meta.kind === 'makeup' ? 'Luxury Makeup' : 'Luxury Care';
  const typeAr = meta.typeAr || meta.familyAr || 'منتج فاخر';
  const typeEn = meta.typeEn || meta.familyEn || 'Luxury product';
  const notesBlockAr = meta.notesAr
    ? `\n◆ نوتات العطر: ${meta.notesAr}`
    : '';
  const notesBlockEn = meta.notesEn
    ? `\n◆ Notes: ${meta.notesEn}`
    : '';
  return {
    descriptionAr: `${meta.introAr}\n\n◆ التصنيف: بريميوم — ${catAr}\n◆ نوع المنتج: ${typeAr}${notesBlockAr}`,
    descriptionEn: `${meta.introEn}\n\n◆ Category: Premium — ${catEn}\n◆ Product type: ${typeEn}${notesBlockEn}`,
  };
}

export function applyPremiumMeta(barcode, names = {}, detail = {}) {
  const meta = getPremiumMeta(barcode);
  if (!meta) return { names, meta: null };
  return {
    meta,
    names: {
      brandAr: meta.brandAr,
      brandEn: meta.brandEn,
      nameAr: meta.nameAr,
      nameEn: meta.nameEn,
      productAr: meta.nameAr.replace(/^[^-]+-\s*/, ''),
      productEn: meta.nameEn.replace(/^[^ ]+\s*/, ''),
    },
  };
}
